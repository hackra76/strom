export function translateHelpText(text: string): string {
    let out = text;
    for (const [pattern, replacement] of PHRASE_RULES) {
        out = out.replace(pattern, (m) => applyCasePattern(m, replacement));
    }
    out = out.replace(WORD_REGEX, (m) => {
        const mapped = WORD_MAP[m.toLowerCase()];
        return mapped ? applyCasePattern(m, mapped) : m;
    });
    return out;
}

function translateInline(inline: HelpInline): HelpInline {
    if (typeof inline === 'string') return translateHelpText(inline);
    if ('code' in inline) return inline;
    if ('b' in inline) return { b: translateHelpText(inline.b) };
    if ('i' in inline) return { i: translateHelpText(inline.i) };
    if ('ref' in inline) return { ref: inline.ref, t: translateHelpText(inline.t) };
    if ('url' in inline) return { url: inline.url, t: translateHelpText(inline.t) };
    return inline;
}

function translateInlines(arr: HelpInline[]): HelpInline[] {
    return arr.map(translateInline);
}

function translateMetaLabel(label: string): string {
    if (label === 'Ovládání') return 'Ovládanie';
    return translateHelpText(label);
}

function translateBlock(block: HelpBlock): HelpBlock {
    switch (block.k) {
        case 'code':
            return block;
        case 'h':
            return { ...block, title: translateHelpText(block.title) };
        case 'p':
            return { k: 'p', c: translateInlines(block.c) };
        case 'ul':
        case 'ol':
            return {
                k: block.k,
                items: block.items.map(translateInlines),
                sub: block.sub?.map(s => (s ? (translateBlock(s) as typeof s) : null)),
            };
        case 'table':
            return {
                k: 'table',
                head: block.head.map(translateHelpText),
                rows: block.rows.map(row => row.map(translateInlines)),
            };
        case 'meta':
            return {
                k: 'meta',
                items: block.items.map(it => ({
                    ...it,
                    label: translateMetaLabel(it.label),
                    c: translateInlines(it.c),
                })),
            };
        case 'quote':
            return { k: 'quote', blocks: block.blocks.map(translateBlock) };
    }
}

export function translateHelpToSlovak(data: HelpLangData): HelpLangData {
    return {
        parts: data.parts.map(p => ({
            ...p,
            title: PART_TITLES[p.id] ?? translateHelpText(p.title),
        })),
        chapters: data.chapters.map(ch => {
            const ov = CHAPTER_TITLES[ch.id];
            return {
                ...ch,
                title: ov?.title ?? translateHelpText(ch.title),
                desc: ov?.desc ?? translateHelpText(ch.desc),
                intro: translateHelpText(ch.intro),
                introC: translateInlines(ch.introC),
                blocks: ch.blocks.map(translateBlock),
            };
        }),
        terms: data.terms.map(term => ({
            ...term,
            term: translateHelpText(term.term),
            def: translateHelpText(term.def),
        })),
    };
}
