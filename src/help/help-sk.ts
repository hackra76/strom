function applyCasePattern(template: string, replacement: string): string {
    if (!template) return replacement;
    const isAllUpper = template.length > 1 && template === template.toLocaleUpperCase('sk-SK')
        && template !== template.toLocaleLowerCase('sk-SK');
    if (isAllUpper) return replacement.toLocaleUpperCase('sk-SK');
    const first = template.charAt(0);
    if (first === first.toLocaleUpperCase('sk-SK') && first !== first.toLocaleLowerCase('sk-SK')) {
        return replacement.charAt(0).toLocaleUpperCase('sk-SK') + replacement.slice(1);
    }
    return replacement;
}

